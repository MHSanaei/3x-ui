export interface ColoPlace {
  country: string;
  countryName: string;
  city: string;
}

// The browser names the country in the panel's language; only Persian has its own city names.
export function coloPlace(colo: string, lang: string): ColoPlace | null {
  const hit = COLOS[colo];
  if (!hit) return null;
  const [country, en, fa] = hit;
  let name = country;
  try {
    name = new Intl.DisplayNames([lang], { type: 'region' }).of(country) ?? country;
  } catch {
    // an unknown locale keeps the code
  }
  return { country, countryName: name, city: lang.startsWith('fa') ? fa : en };
}

export function flagOf(country: string): string {
  return String.fromCodePoint(...[...country].map((c) => 0x1f1a5 + c.charCodeAt(0)));
}
